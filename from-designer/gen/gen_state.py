#!/usr/bin/env python3
"""gen_state.py — emit CLASS-STATE from classes.json. Do not hand-edit the output.

⚠ WHY THIS EXISTS. The roster count was quoted at 37 in three documents and was
wrong in all three (PT-157). A hand-maintained state list is the thing this
project has repeatedly found drifts: 'derived counts and automated checks are
necessary; never trust a stated count without deriving it.'

Everything below is computed. Capstones, band checks, the droid cap list, the
authored-departure list and every total are derived from the data, not typed.
"""
import json, math, sys, datetime

D = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'classes.json'))
C = D['classes']
PICKS = {'Combat': 36, 'Middle': 27, 'Specialist': 18}
BAND_N = {'Combat': (14, 20), 'Middle': (11, 17), 'Specialist': (8, 14)}
BAND_SK = {'Combat': (1, 4), 'Middle': (2, 5), 'Specialist': (3, 7)}
BAND_FT = {'Combat': (18, 23), 'Middle': (15, 16), 'Specialist': (10, 12)}
DROID_CAP = 11
CREDITS = 4

def T(c):   return PICKS[c['rate']] + CREDITS if c.get('rate') else None
def caps(c):
    return (T(c) - c['N']) // 2 if c.get('rate') and c.get('N') else None

def problems(c):
    """Every check is derived. None of these is a typed assertion."""
    p = []
    if not c.get('rate'):
        return p
    t = T(c)
    if c.get('N'):
        lo, hi = BAND_N[c['rate']]
        if not lo <= c['N'] <= hi:
            p.append(f"chain count {c['N']} outside {c['rate']} band {lo}-{hi}")
        if 3 * c['N'] < t:
            p.append(f"STRANDS {t - 3*c['N']} tiers")
    if c.get('skill') is not None:
        lo, hi = BAND_SK[c['rate']]
        if not lo <= c['skill'] <= hi:
            p.append(f"skill base {c['skill']} outside {c['rate']} band {lo}-{hi}")
    if c.get('feats'):
        lo, hi = BAND_FT[c['rate']]
        if not lo <= c['feats'] <= hi:
            p.append(f"feats {c['feats']} outside {c['rate']} band {lo}-{hi}")
    return p

out = []
w = out.append
w("# CLASS-STATE — generated\n")
w(f"> **⚠ Generated by `gen_state.py` from `classes.json`. Do not hand-edit — regenerate.**\n")
w(f"**{len(C)} classes.** *Status: **A** adopted · **P** pushed, unconfirmed · **X** unresolved.*")
w(f"**Saves are Fort / Reflex / Will at 20 — `PT-119`: Strong 12, Hybrid 9, Weak 6.**\n")

for g in ['standard base', 'Force base', 'standard prestige', 'Force prestige']:
    rows = [c for c in C if c['g'] == g]
    w(f"\n## {g.title()} — {len(rows)}\n")
    w("| Class | | Rate | Die | Force | Pri | Feats | Chains | Caps | Skill | Saves | Entry | Identity |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c in rows:
        f = lambda k, d='—': (c.get(k) if c.get(k) not in (None, '') else d)
        w(f"| **{c['n']}** | {c['s']} | {f('rate')} | {f('die')} | {f('fd')} | {f('pri')} | "
          f"{f('feats')} | {f('N')} | {caps(c) or '—'} | {f('skill')} | {f('sv')} | "
          f"{f('entry')} | {c['id']} |")

w("\n---\n\n# Derived checks\n")
bad = [(c['n'], p) for c in C for p in [problems(c)] if p]
w(f"**Band and stranding checks across {len([c for c in C if c.get('rate')])} classes with a rate:**\n")
if bad:
    for n, p in bad:
        w(f"- **{n}** — ⚠ {'; '.join(p)}")
else:
    w("- all pass")

w(f"\n**⚠ Zero slack against `PT-114`'s droid cap of {DROID_CAP} chains** — raising any by one closes it to droids:\n")
for c in C:
    if c.get('N') == DROID_CAP:
        w(f"- {c['n']}")

w("\n**⚠ Authored feat totals — the source has no Force class above 16:**\n")
src = {'Jedi Guardian': 16, 'Sith Warrior': 16, 'Sith Assassin': 10,
       'Jedi Weaponmaster': 16, 'Sith Battlemaster': 16, 'Marksman': 11}
for c in C:
    if c['n'] in src and c.get('feats') and c['feats'] != src[c['n']]:
        w(f"- {c['n']}: **{c['feats']}** authored, source {src[c['n']]}")

w("\n**Not drafted:**\n")
for c in C:
    if c['s'] == 'X':
        w(f"- **{c['n']}** — {c.get('flag','')}")

w("\n**Every flag carried in the data:**\n")
for c in C:
    if c.get('flag'):
        w(f"- **{c['n']}** — {c['flag']}")

w(f"\n---\n\n*{len(C)} classes · "
  f"{sum(1 for c in C if c['s']=='A')} adopted · "
  f"{sum(1 for c in C if c['s']=='P')} pushed · "
  f"{sum(1 for c in C if c['s']=='X')} unresolved*")
print('\n'.join(out))
